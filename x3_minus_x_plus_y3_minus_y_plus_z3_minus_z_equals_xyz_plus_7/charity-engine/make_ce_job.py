#!/usr/bin/env python3
"""Builds ce_job.sh: one self-contained file to upload as the input file of a Charity Engine reservation.

It embeds ../src/k7.c, workunits.txt and run_job.sh. On the host it compiles the program with gcc (the stock
docker:python and docker:gcc images both have it), self-tests, runs the requested work units, and prints the results
to stdout as "K7RESULT ..." lines (and writes result_<id>.txt files in the working directory).

Usage: python3 make_ce_job.py        (writes ce_job.sh next to this file)
"""
import os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', 'src', 'k7.c')).read()
wus = open(os.path.join(here, 'workunits.txt')).read()
runjob = open(os.path.join(here, 'run_job.sh')).read()
for name, text in (('k7.c', src), ('workunits.txt', wus), ('run_job.sh', runjob)):
    assert 'EOF_K7_EMBEDDED' not in text, name

head = r'''#!/bin/bash
# Charity Engine job: complete search for integer solutions of  x^3 - x + y^3 - y + z^3 - z = xyz + 7
# Upload this file as the reservation's input file.  App: docker:python  (or docker:gcc)
# Command line examples:
#   bash %INPUTFILE1% --selftest          compile + self-test only (~1 min), to check the setup
#   bash %INPUTFILE1% --range 0 8         work units 0..7 of the 656 (8 units: about 4-6 h on 2 vCPUs)
#   bash %INPUTFILE1% --job 5 8           job number 5 with 8 units each, i.e. units 40..47
#   bash %INPUTFILE1% 17 18 19            explicit work units
# Output: "K7RESULT <unit> STATUS COMPLETE" + "TOTALS ..." lines on stdout per unit; any solution as a SOLUTION line.
#   bash %INPUTFILE1% --hours 4 --job 5 4 if the job time limit is 4 h (default assumes 8 h)
# Env: MAX_HOURS (default 7.5) - no new unit is started when the budget is nearly used; THREADS (default: all CPUs).
# Generated by make_ce_job.py from ../src/k7.c, workunits.txt and run_job.sh - edit those, not this file.
START=$PWD
W=$(mktemp -d 2>/dev/null) || { W=/tmp/k7job$$; mkdir -p "$W"; }
'''
body = (f"cat > \"$W/k7.c\" << 'EOF_K7_EMBEDDED'\n{src}EOF_K7_EMBEDDED\n"
        f"cat > \"$W/workunits.txt\" << 'EOF_K7_EMBEDDED'\n{wus}EOF_K7_EMBEDDED\n"
        f"cat > \"$W/run_job.sh\" << 'EOF_K7_EMBEDDED'\n{runjob}EOF_K7_EMBEDDED\n")
tail = r'''cd "$W" || exit 4
NCPU=$(nproc 2>/dev/null || echo 1)
echo "K7RESULT HOST cpus=$NCPU mem_kB=$(awk '/MemTotal/{print $2}' /proc/meminfo 2>/dev/null) cpu=\"$(awk -F: '/model name/{print $2; exit}' /proc/cpuinfo 2>/dev/null | sed 's/^ *//')\" avx512ifma=$(grep -qw avx512ifma /proc/cpuinfo 2>/dev/null && echo yes || echo no)"
command -v gcc >/dev/null || { echo "K7RESULT NO_COMPILER: use App docker:python or docker:gcc"; exit 4; }
if gcc -O3 -march=native -o k7_generic k7.c -lm -lpthread 2>build.log && gcc -O3 -march=native -DK=41 -o k7_41_generic k7.c -lm -lpthread 2>>build.log; then
  echo "K7RESULT BUILD native"
elif gcc -O3 -o k7_generic k7.c -lm -lpthread 2>>build.log && gcc -O3 -DK=41 -o k7_41_generic k7.c -lm -lpthread 2>>build.log; then
  echo "K7RESULT BUILD portable"
else
  echo "K7RESULT COMPILE_FAILED $(head -c 400 build.log | tr '\n' ' ')"; exit 4
fi
O=$START; [ -w "$O" ] || O=$W
if [ "${1:-}" = "--hours" ]; then export MAX_HOURS=$(awk -v h="$2" 'BEGIN{print (h>0.6? h-0.5 : h)}'); shift 2; fi   # stop starting units ~30 min before the job limit
if [ "${1:-}" = "--selftest" ]; then
  rm -f /tmp/k7_selftest_ok_*                                             # always really run the self-test here
  K7DIR=$W OUT=$O bash "$W/run_job.sh" 99999 > "$W/st.out" 2>&1          # 99999 is no real unit: self-test only
  grep -v "^K7RESULT 99999 " "$W/st.out"
  if grep -q SELFTEST_OK "$W/st.out"; then echo "K7RESULT SETUP_OK"; exit 0; else exit 3; fi
fi
[ "${1:-}" = "--job" ] && { [ $# -ge 3 ] || { echo "usage: --job N PER"; exit 2; }; set -- --range $(( $2 * $3 )) "$3"; }
K7DIR=$W OUT=$O bash "$W/run_job.sh" "$@"
exit $?
'''
out = os.path.join(here, 'ce_job.sh')
open(out, 'w').write(head + body + tail)
os.chmod(out, 0o755)
print("wrote", out, os.path.getsize(out), "bytes")
